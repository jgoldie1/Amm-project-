'use strict';
const assert=require('node:assert/strict');
const lifecycle=require('../lib/tryamm-order-lifecycle');
const uuid='11111111-2222-4333-8444-555555555555';
const proposal={campaignId:uuid,leadId:'22222222-2222-4222-8222-222222222222',packageId:'preview',description:'Accessible branded website preview, one Reel and mobile review.',terms:'Two revisions, agreed delivery schedule, cancellation and support terms.'};
const order=lifecycle.newOrder('customer1',proposal);
assert.equal(order.price_cents,49900);
assert.equal(order.status,'quote-pending');
assert.equal(order.verified_paid_at,null);
assert.throws(()=>lifecycle.validateProposal({...proposal,packageId:'free'}),/supported paid/);
assert.throws(()=>lifecycle.validateProposal({...proposal,leadId:'another-customer'}),/Valid lead/);
assert.throws(()=>lifecycle.ownerTransition(order,'paid-verified',{actorRole:'admin',verifiedPayment:true}),/Invalid order transition/);
assert.throws(()=>lifecycle.ownerTransition(order,'quote-approved',{actorRole:'member'}),/Owner permission/);
const approved=lifecycle.ownerTransition(order,'quote-approved',{actorRole:'admin'});
assert.equal(approved.status,'quote-approved');
const quote={...order,...approved};
assert.throws(()=>lifecycle.ownerTransition(quote,'customer-accepted',{actorRole:'admin'}),/Customer acceptance/);
const accepted={...quote,...lifecycle.ownerTransition(quote,'customer-accepted',{actorRole:'admin',customerAcceptance:true})};
const pending={...accepted,...lifecycle.ownerTransition(accepted,'payment-pending',{actorRole:'admin'})};
assert.throws(()=>lifecycle.ownerTransition(pending,'paid-verified',{actorRole:'admin'}),/Provider-verified/);
const paid={...pending,...lifecycle.ownerTransition(pending,'paid-verified',{actorRole:'admin',verifiedPayment:true})};
assert.ok(paid.verified_paid_at);
const building={...paid,...lifecycle.ownerTransition(paid,'building',{actorRole:'admin'})};
const reviewing={...building,...lifecycle.ownerTransition(building,'review-ready',{actorRole:'admin'})};
assert.throws(()=>lifecycle.ownerTransition(reviewing,'delivered',{actorRole:'admin'}),/Verified payment and customer delivery evidence/);
assert.equal(lifecycle.ownerTransition(reviewing,'delivered',{actorRole:'admin',deliveryEvidence:true}).status,'delivered');
console.log('Website OS order lifecycle, invoice amount, ownership, customer acceptance, payment and delivery guards: PASS');
