'use strict'
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path')
const root=path.resolve(__dirname,'../amm-omniverse/src')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const catalog=read('data/FaithVerseAncientStories.ts')
const theater=read('components/FaithVerseAncientStoriesTheater.tsx')
const hub=read('components/FaithVerseBibleHub.tsx')
const water=read('components/FaithVerseWaterWalk3D.tsx')
const miracle=read('components/FaithVerseMiraclesTheater.tsx')
const ai=read('components/AICommonsOnePush.tsx')
const studio=read('components/CommonsStreetVerseCharacterStudio.tsx')
const printer=read('components/TRYAMMPrintStudio.tsx')
for(const label of ['Noah, the Ark and the Great Flood','Nephilim and Giants','The Watchers and Fallen-Angel Tradition','David and Goliath','Tower of Babel','Crossing of the Sea'].slice(0,4))assert.ok(catalog.includes(label),label)
for(const scripture of ['Genesis 6:1–4','Numbers 13:32–33','1 Enoch 6–15','1 Samuel 17:1–58','Genesis 7:1–24'])assert.ok(catalog.includes(scripture),scripture)
assert.ok(catalog.includes('verifiedRiggedGLB:false'))
for(const term of ['contentLevel','Teen · intimidating fictional giants','Family · gentler scenes','StoryView','age','Save checkpoint'])assert.ok(theater.includes(term),term)
assert.ok(hub.includes('FaithVerseAncientStoriesTheater'))
for(const term of ['THREE.WebGLRenderer','THREE.SkinnedMesh','THREE.Skeleton','PlaneGeometry','prefers-reduced-motion','WebGL unavailable','not a verified 3D Yeshua GLB'])assert.ok(water.includes(term),term)
assert.ok(miracle.includes('FaithVerseWaterWalk3D'))
for(const term of ['CommonsStreetVerseCharacterStudio','TRYAMMPrintStudio'])assert.ok(ai.includes(term),term)
assert.ok(studio.includes('No network NPC was spawned'))
assert.ok(printer.includes('No printer device is connected'))
const gates=require('../lib/commons-streetverse-agent-contract')
assert.equal(gates.validateCharacter({name:'School Guide',role:'teacher',world:'campusverse',bio:'Offers study hints'}).ok,true)
assert.equal(gates.validateCharacter({name:'Fake doctor',role:'guide',world:'streetverse',bio:'prescribe pills'}).ok,false)
assert.equal(gates.actionAllowed({isAI:true,world:'streetverse'},{type:'greet',world:'streetverse'}).allowed,true)
assert.equal(gates.actionAllowed({isAI:true,world:'streetverse'},{type:'transfer_money',world:'streetverse'}).allowed,false)
const realtime=require('../lib/faithverse-realtime-room')
assert.equal(realtime.canJoin({enabled:false,user:{id:'one'},roomId:'galilee-study',role:'witness'}).ok,false)
assert.equal(realtime.canJoin({enabled:true,user:{id:'one'},roomId:'galilee-study',role:'witness'}).ok,true)
assert.equal(realtime.canJoin({enabled:true,user:null,roomId:'galilee-study',role:'witness'}).ok,false)
assert.equal(realtime.canJoin({enabled:true,user:{id:'one'},roomId:'private-medical',role:'witness'}).ok,false)
console.log('FaithVerse stories, 3D prototype, Commons NPC, print studio and multiplayer gates PASS')
