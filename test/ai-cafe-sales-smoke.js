'use strict';
const assert=require('node:assert/strict');
const {createLead,approveQuote,applyVerifiedCafeCheckout,summary}=require('../lib/ai-cafe-sales');
const store={};
assert.throws(()=>createLead(store,{email:'a@example.com',interest:'Website'}),/consent/);
const lead=createLead(store,{email:'customer@example.com',interest:'TRYAMM website',locale:'es',consent:true,campaignId:'test'});
assert.equal(lead.locale,'es');
assert.equal(lead.status,'new');
assert.throws(()=>approveQuote(store,{leadId:lead.id,priceCents:0,approvedBy:'owner'}),/priceCents/);
const quote=approveQuote(store,{leadId:lead.id,priceCents:49900,currency:'usd',approvedBy:'owner'});
assert.equal(lead.status,'quoted');
assert.throws(()=>approveQuote(store,{leadId:lead.id,priceCents:49900,approvedBy:'owner'}),/already exists/);
quote.stripeSessionId='cs_test_1';
const session={id:'cs_test_1',mode:'payment',payment_status:'unpaid',amount_total:49900,currency:'usd',metadata:{kind:'ai-cafe-service',leadId:lead.id,quoteId:quote.id}};
const unpaid=applyVerifiedCafeCheckout(store,session);assert.equal(unpaid.applied,false);
assert.equal(summary(store).verifiedGrossCents,0);
assert.equal(summary(store).pendingChainAnchors,0);
assert.throws(()=>applyVerifiedCafeCheckout(store,{...session,payment_status:'paid',amount_total:19900}),/does not match/);
assert.equal(summary(store).verifiedGrossCents,0);
const paid=applyVerifiedCafeCheckout(store,{...session,payment_status:'paid'},{eventId:'evt_test'});
assert.equal(paid.applied,true);
assert.equal(paid.anchor.status,'PENDING_SERVER_CHAIN_ANCHOR');
assert.match(paid.anchor.payloadSha256,/^[a-f0-9]{64}$/);
assert.equal(summary(store).verifiedGrossCents,49900);
assert.equal(summary(store).chainAnchorsVerified,0);
const again=applyVerifiedCafeCheckout(store,{...session,payment_status:'paid'},{eventId:'evt_test'});
assert.equal(again.reason,'ALREADY_APPLIED');
assert.equal(summary(store).verifiedSales,1);
assert.equal(summary(store).pendingChainAnchors,1);
assert.equal(lead.status,'customer');
assert.equal(applyVerifiedCafeCheckout(store,{metadata:{kind:'other'}}).handled,false);
console.log('AI Cafe sales and pending evidence smoke: PASS');
