'use strict';
const assert=require('node:assert/strict');
const {GATES,inventoryAudit,auditRelease}=require('../lib/tryamm-release-certification');
assert.equal(GATES.length,11);
const first=auditRelease();
assert.equal(first.earned,0);
assert.equal(first.productionCertified,false);
assert.equal(first.inventory.recordCount,0);
const thirty=Array.from({length:30},(_,index)=>({id:'site_'+(index+1),name:'Synthetic test site '+(index+1),evidence:{publicUrlVerified:true,mobileTestPassed:true,customerJourneyTestPassed:true}}));
const audit=inventoryAudit(thirty);
assert.equal(audit.valid,true);
assert.equal(audit.publicVerified,30);
assert.equal(inventoryAudit([...thirty.slice(0,29),thirty[0]]).valid,false);
const evidence=Object.fromEntries(GATES.map(([key])=>[key,{passed:true,reference:'test://ci/'+key,verifiedAt:'2026-11-01T00:00:00Z'}]));
const complete=auditRelease({sites:thirty,evidence});
assert.equal(complete.earned,11);
assert.equal(complete.productionCertified,true);
const missing=auditRelease({sites:thirty,evidence:{...evidence,payments:{passed:false}}});
assert.equal(missing.earned,10);
assert.equal(missing.productionCertified,false);
const partial=auditRelease({sites:thirty.slice(0,29),evidence});
assert.equal(partial.productionCertified,false);
assert.equal(partial.gates.find(x=>x.id==='inventory').status,'BLOCKED');
console.log('TRYAMM 11/11 evidence gates and 30-site inventory smoke: PASS');
