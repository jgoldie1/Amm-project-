'use strict';
const assert=require('assert');
process.env.SECURITY_VAULT_KEY='test-security-vault-key-that-is-not-used-in-production';
process.env.SESSION_TOKEN_PEPPER='test-session-pepper';
process.env.STEP_UP_TOKEN_PEPPER='test-stepup-pepper';
const vault=require('../lib/security-vault');
const step=require('../lib/step-up-security');
const secret=step.totpSecret();
const enc=vault.encrypt(secret);
assert(enc.ciphertext&&enc.iv&&enc.tag);
const fake={totp_secret_ciphertext:enc.ciphertext,totp_secret_iv:enc.iv,totp_secret_tag:enc.tag};
assert.equal(vault.decryptFields(fake,'totp_secret'),secret);
const issued=step.issue({userId:'u1',sessionId:'s1',action:'change-payout-destination',method:'totp',now:1000});
assert(issued.record.tokenHash);
assert.notEqual(issued.record.tokenHash,issued.token);
assert.equal(step.hmac(issued.token),issued.record.tokenHash);
const code=step.totpCode(secret,{time:1700000000000});
assert(step.verifyTotp(secret,code,{time:1700000000000}));
console.log('security vault smoke: PASS');
