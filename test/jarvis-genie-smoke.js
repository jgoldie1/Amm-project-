'use strict';
const assert=require('node:assert/strict');
const {planIntent}=require('../lib/jarvis-genie-intent');
const inquiry=planIntent('Show my AI Café leads');
assert.equal(inquiry.target,'sales');
assert.equal(inquiry.status,'NO_ACTION');
assert.equal(inquiry.action,'show-existing-route');
assert.equal(inquiry.requiresOwnerApproval,false);
const payment=planIntent('Pay my bill');
assert.equal(payment.status,'NO_ACTION');
assert.equal(payment.requiresOwnerApproval,true);
assert.equal(payment.action,'draft-for-review');
const ambiguous=planIntent('Post my StreetVerse campaign');
assert.equal(ambiguous.action,'choose-target');
assert.equal(ambiguous.status,'NO_ACTION');
const unknown=planIntent('Read my thoughts');
assert.equal(unknown.action,'clarify');
assert.equal(unknown.status,'NO_ACTION');
assert.equal(planIntent('').ok,false);
console.log('JARVIS Genie safe intent routing: PASS');
