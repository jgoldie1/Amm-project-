'use strict';
const assert=require('node:assert/strict');
const funnel=require('../lib/tryamm-funnel-contract');
const base={projectId:'11111111-2222-4333-8444-555555555555',name:'Stubb Mobility Holo Reel',offer:'Accessible technology consultation',landingUrl:'https://customer-owned.example.org/services'};
const campaign=funnel.validateCampaign(base);
assert.equal(campaign.status,'draft');
assert.throws(()=>funnel.validateCampaign({...base,landingUrl:'http://localhost:3000'}),/HTTPS/);
assert.throws(()=>funnel.validateCampaign({...base,projectId:'../../private'}),/project/);
assert.throws(()=>funnel.validateLead({email:'x@example.com',interest:'quote',consent:false,website:''}),/consent/);
assert.throws(()=>funnel.validateLead({email:'x@example.com',interest:'quote',consent:true,website:'bot'}),/rejected/);
assert.equal(funnel.validateLead({email:'buyer@example.com',interest:'Website request',consent:true,website:''}).email,'buyer@example.com');
assert.equal(funnel.gate({}).ready,false);
const complete=Object.fromEntries(funnel.checks.map(key=>[key,{passed:true,reference:'evidence://review-'+key}]));
assert.equal(funnel.gate({evidence:complete}).ready,true);
const metrics=funnel.measurements({visits:100,leads:5,quotes:2,paidSales:1,verifiedGrossCents:49900});
assert.equal(metrics.visitorToLeadRate,0.05);
assert.equal(metrics.leadToPaidRate,0.2);
assert.equal(funnel.measurements().verifiedSales,0);
console.log('TRYAMM Holo Reel to storefront funnel contract: PASS');
