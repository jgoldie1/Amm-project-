'use strict';
const assert=require('assert');
const {gates,requiredFor,evaluatePromotion,certificationScore}=require('../lib/world-certification');
assert.strictEqual(gates.policy,'deny-promotion-until-evidence');
assert(requiredFor('PRODUCTION_CERTIFIED').includes('rollback-verified'));
assert(requiredFor('PRODUCTION_CERTIFIED').includes('observability-ready'));
let result=evaluatePromotion({fromStatus:'PLAYABLE',toStatus:'ECONOMY_ENABLED',evidence:[]});
assert.strictEqual(result.allowed,false);
assert(result.missing.includes('server-authoritative-ledger'));
result=evaluatePromotion({fromStatus:'PLAYABLE',toStatus:'ECONOMY_ENABLED',evidence:requiredFor('ECONOMY_ENABLED')});
assert.strictEqual(result.allowed,true);
result=evaluatePromotion({fromStatus:'ECONOMY_ENABLED',toStatus:'PRODUCTION_CERTIFIED',evidence:requiredFor('PRODUCTION_CERTIFIED'),flags:{missingRollback:true}});
assert.strictEqual(result.allowed,false);
assert.strictEqual(result.reason,'HARD_BLOCK');
result=evaluatePromotion({fromStatus:'DATA_READY',toStatus:'PLAYABLE',evidence:requiredFor('PLAYABLE')});
assert.strictEqual(result.allowed,false);
assert.strictEqual(result.reason,'PROMOTION_MUST_BE_SEQUENTIAL');
const score=certificationScore(Object.values(gates.requiredEvidence).flat());
assert.strictEqual(score.percent,100);
console.log('World certification gates, hard blocks and evidence scoring checks passed');
