'use strict'
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.join(__dirname,'../amm-omniverse/src')
const read=x=>fs.readFileSync(path.join(root,x),'utf8')
async function main(){
 const mod=await import('../amm-omniverse/src/runtime/StreetVerseVehicleDynamics.mjs')
 let car=mod.createVehicleState('car')
 assert.equal(car.gear,'P')
 for(let i=0;i<180;i++)car=mod.stepVehicle(car,{gear:'D',throttle:1},1/60)
 assert.ok(car.speed>5,'car should accelerate forward')
 assert.ok(car.z>0,'car should move forward')
 const before=car.speed
 for(let i=0;i<100;i++)car=mod.stepVehicle(car,{gear:'D',brake:1},1/60)
 assert.ok(car.speed<before,'brakes should slow car')
 const stopped=mod.simulateVehicle(mod.createVehicleState('car'),{gear:'D',throttle:0},1)
 assert.equal(stopped.speed,0)
 let bike=mod.createVehicleState('motorcycle')
 for(let i=0;i<210;i++)bike=mod.stepVehicle(bike,{gear:'D',throttle:1,steer:.7},1/60)
 assert.ok(bike.speed>5)
 assert.ok(Math.abs(bike.lean)>.001,'bike should lean while cornering')
 const parked=mod.simulateVehicle(bike,{gear:'P',parkingBrake:true,brake:1},.5)
 assert.notEqual(parked.gear,'P','should not allow parking shift while rolling')
 const telemetry=mod.safeVehicleTelemetry(bike)
 assert.equal(telemetry.networkSynced,false)
 assert.equal(telemetry.rapierCollisionIntegrated,false)
 assert.throws(()=>mod.stepVehicle(bike,{},-1),/INVALID_FIXED_TIMESTEP/)
 assert.throws(()=>mod.createVehicleState('helicopter'),/VEHICLE_KIND_UNSUPPORTED/)
 const world=read('components/StreetVerseMobileWorld.tsx')
 const driving=read('components/StreetVerseVehicleDynamicsHUD.tsx')
 for(const t of ['StreetVerseVehicleDynamicsHUD', '<StreetVerseVehicleDynamicsHUD/>'])assert.ok(world.includes(t),t)
 for(const t of ['HOLD ACCELERATE','HOLD BRAKE','MOTORCYCLE','STEER LEFT','tryamm:streetverse-transmission','PARKING BRAKE','onPointerCancel','ONE'])if(t!=='ONE')assert.ok(driving.includes(t),t)
 const stories=read('data/FaithVerseAncientStories.ts')
 const theater=read('components/FaithVerseAncientStoriesTheater.tsx')
 const quest=read('components/FaithVerseAncientQuestControls.tsx')
 for(const t of ['Genesis 6:1–4','1 Enoch 6–15','1 Samuel 17:1–58','Genesis 7:1–24','FAITHVERSE_CREATURE_DESIGNS','crooked fantasy teeth','ragged shadow feathers','castingSafeguard'])assert.ok(stories.includes(t),t)
 for(const t of ['story.stageAge','contentLevel','FAITHVERSE_CREATURE_DESIGNS','FaithVerseAncientQuestControls'])assert.ok(theater.includes(t),t)
 for(const t of ['GUIDE ANIMALS TO SHELTER','OBSERVE FICTIONAL GIANTS','COMPARE 1 ENOCH','PRACTICE TARGET CHALLENGE','hasFinancialValue:false','cloudPersisted:false'])assert.ok(quest.includes(t),t)
 console.log('StreetVerse vehicle dynamics + FaithVerse Flood/Nephilim/Watchers/David regression PASS')
}
main().catch(e=>{console.error(e);process.exitCode=1})
