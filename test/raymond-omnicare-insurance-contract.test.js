'use strict'
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const {SERVICES,assessService}=require('../lib/raymond-insurance-service-gates')
assert.ok(Object.keys(SERVICES).length>=6)
for(const service of ['insurance_education','retirement_401k_education','infinite_banking_education','legacy_planning_referral','omnicare_insurance_navigation'])
 assert.equal(assessService({service,action:'view_service_description'}).allowed,true,service)
for(const action of ['diagnosis','treatment','prescription','live_trade','manage_401k_assets','guaranteed_returns','automated_policies','collect_health_history'])
 assert.equal(assessService({service:'insurance_education',action}).allowed,false,action)
assert.equal(assessService({service:'clinical_telehealth',action:'view_service_description'}).allowed,false)
for(const flag of ['containsHealthData','hasPaymentInfo','hasAccountCredentials'])
 assert.equal(assessService({service:'insurance_education',action:'public_education',[flag]:true}).allowed,false,flag)
const component=fs.readFileSync(path.join(__dirname,'../amm-omniverse/src/components/OmniCare360CareAccess.tsx'),'utf8')
const preview=fs.readFileSync(path.join(__dirname,'../amm-omniverse/src/components/RaymondJarreauLaunchPreview.tsx'),'utf8')
const site=fs.readFileSync(path.join(__dirname,'../amm-omniverse/public/raymond-jarreau-preview.html'),'utf8')
for(const name of ['Raymond Jarreau','401(k)','infinite banking'])assert.ok(component.toLowerCase().includes(name.toLowerCase()),name)
for(const name of ['Insurance','401(k)','Infinite Banking'])assert.ok(preview.includes(name),name)
for(const name of ['insurance','401(k)','infinite banking'])assert.ok(site.toLowerCase().includes(name.toLowerCase()),name)
assert.ok(site.includes('noindex,nofollow'))
assert.ok(component.includes('Clinical services are not active'))
console.log('Raymond insurance/retirement service separation and OmniCare360 nonclinical policies PASS')
