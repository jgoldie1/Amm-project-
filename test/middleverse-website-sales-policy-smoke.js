'use strict';
const assert=require('node:assert/strict');
const {createWebsiteLead,canPublishCreatorLink}=require('../lib/middleverse-website-sales-policy');
const input={businessId:'biz_1',businessName:'Example Salon',contactEmail:'owner@example.com',category:'beauty',plan:'starter'};
const unapproved=createWebsiteLead(input,{});
assert.equal(unapproved.valid,true);
assert.equal(unapproved.displayOffer,null);
assert.equal(unapproved.canCreateCheckout,false);
assert.equal(unapproved.paid,false);
const approved=createWebsiteLead(input,{offersApproved:true,pricesApproved:true,pricesCents:{starter:19900}});
assert.equal(approved.displayOffer.priceCents,19900);
assert.equal(approved.canCreateCheckout,true);
assert.equal(approved.lead.paymentStatus,'not_requested');
assert.equal(createWebsiteLead({...input,contactEmail:'bad'}).valid,false);
assert.equal(createWebsiteLead({...input,plan:'made-up'}).canCreateCheckout,false);
assert.equal(createWebsiteLead(input,{offersApproved:true,pricesApproved:true,pricesCents:{starter:-1}}).canCreateCheckout,false);
assert.equal(canPublishCreatorLink({approved:true,moderationPassed:true,targetUrl:'https://tryamm.online/shop',allowedHosts:['tryamm.online']}),true);
assert.equal(canPublishCreatorLink({approved:true,moderationPassed:false,targetUrl:'https://tryamm.online/shop',allowedHosts:['tryamm.online']}),false);
assert.equal(canPublishCreatorLink({approved:true,moderationPassed:true,targetUrl:'https://tryamm.online.evil.test/shop',allowedHosts:['tryamm.online']}),false);
assert.equal(canPublishCreatorLink({approved:true,moderationPassed:true,targetUrl:'http://tryamm.online/shop',allowedHosts:['tryamm.online']}),false);
console.log('MiddleVerse website sales policy: 10 checks passed');
