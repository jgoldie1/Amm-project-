#!/usr/bin/env node
// Read-only release inventory validation; never deploys.
const fs = require('node:fs');
const path = require('node:path');
const data = JSON.parse(fs.readFileSync(path.join(__dirname, 'registry.json'), 'utf8'));
const allowed = new Set(['unassigned','planned','building','testing','review','approved','live']);
const seen = new Set(), errors = [], rows = [];
if (!Array.isArray(data.sites) || data.sites.length !== 30) errors.push('Registry must contain exactly 30 slots');
for (const [i,s] of (data.sites || []).entries()) {
  if (s.slot !== i+1) errors.push('Incorrect slot number at index '+i);
  if (!allowed.has(s.status)) errors.push('Invalid status at slot '+s.slot);
  if (s.status !== 'unassigned') {
    if (!s.business || !s.business.trim()) errors.push('Business name missing: '+s.slot);
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(s.slug || '')) errors.push('Invalid slug: '+s.slot);
    if (seen.has(s.slug)) errors.push('Duplicate slug: '+s.slug);
    seen.add(s.slug);
    const p=s.path || '';
    if (!p || path.isAbsolute(p) || p.split(/[\\/]/).includes('..')) errors.push('Missing or unsafe local path: '+s.slot);
    else if (!fs.existsSync(path.resolve(process.cwd(),p))) errors.push('Source path does not exist: '+p);
  }
  rows.push('| '+s.slot+' | '+(s.business||'Unassigned')+' | '+s.status+' | '+(s.path||'—')+' |');
}
const summary=['# 30 Website Readiness Report','','Generated by a read-only GitHub Actions registry check. A passing check does not mean sites are published.','','| Slot | Business | Status | Source path |','|---:|---|---|---|',...rows,'','**Registry issues:** '+errors.length, ...errors.map(x=>'- '+x),''].join('\n');
fs.writeFileSync('website-readiness-report.md',summary);
console.log(summary);
if(errors.length)process.exitCode=1;
