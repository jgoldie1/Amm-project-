import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
const read=(path)=>fs.readFileSync(new URL('../'+path,import.meta.url),'utf8')
test('forging is real native Three.js placement, not a planning-only event',()=>{
 const forge=read('src/runtime/StreetVerseVisibleForgeBridge.ts')
 const mobile=read('src/components/StreetVerseMobileWorld.tsx')
 const builder=read('src/components/StreetVerseWestSideWorldBuilder.tsx')
 assert.match(forge,/source\.clone\(true\)/)
 assert.match(forge,/layer\.add\(clone\)/)
 assert.match(forge,/localStorage\.setItem\(KEY,JSON\.stringify\(records\)\)/)
 assert.match(forge,/export const FORGE_PLACEMENT_LIMIT=24/)
 assert.match(forge,/const allowed=new Set/)
 assert.match(forge,/getNativeLayer/)
 assert.match(forge,/broadcast\(\{preset:d\.preset,status,placed/)
 assert.match(mobile,/installStreetVerseVisibleForgeBridge/)
 assert.match(mobile,/visibleForge\.hydrate\(\)/)
 assert.match(mobile,/visibleForge\.dispose\(\)/)
 assert.match(builder,/PLACE STOREFRONTS/)
 assert.match(builder,/PLACE PARK/)
 assert.match(builder,/PLACE STREET PROPS/)
 assert.match(builder,/UNDO LAST PROP/)
 assert.match(builder,/tryamm:streetverse-forge-placement-result/)
})
test('Taylor travel retains the player, joystick and 3D canvas instead of replacing it',()=>{
 const builder=read('src/components/StreetVerseWestSideWorldBuilder.tsx')
 const mobile=read('src/components/StreetVerseMobileWorld.tsx')
 assert.match(builder,/tryamm:west-side-route-request/)
 assert.doesNotMatch(builder,/new Event\('tryamm:streetverse-open-near-west'\)/)
 assert.match(mobile,/addEventListener\('tryamm:west-side-route-request'/)
 assert.match(mobile,/avatar\.position\.set\(x,0,z\)/)
 assert.match(mobile,/createStreetVerseWestSideVisibleWorld\(scene,externalCollisionBoxes\)/)
 assert.match(mobile,/renderer\.render\(scene,camera\)/)
 const bridge=read('src/components/StreetVerseGeoSpawnBridge.tsx')
 assert.match(bridge,/if\(mobile\)\{window\.dispatchEvent\(new CustomEvent\('tryamm:west-side-route-request'/)
})
test('native self-contained GLBs are generated during production build, independent of paid external APIs',()=>{
 const pkg=JSON.parse(read('package.json'))
 assert.match(pkg.scripts.build,/assets:prebuild/)
 assert.match(pkg.scripts['assets:prebuild'],/native:assets/)
 assert.match(read('scripts/tryamm-native-asset-foundry.mjs'),/creditsUsed:0/)
 assert.match(read('src/data/TryammNativeRuntimeAssetCatalog.ts'),/\/generated-assets\/native\/kit\/brick-building-module\.glb/)
})
