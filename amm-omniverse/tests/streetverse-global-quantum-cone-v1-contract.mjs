import assert from 'node:assert/strict'
import fs from 'node:fs'
const read=p=>fs.readFileSync(new URL(p,import.meta.url),'utf8')
const registry=read('../src/data/StreetVerseGlobalRegistry.ts')
const atlas=read('../src/components/StreetVerseGlobalConeAtlas.tsx')
const cone=read('../src/components/StreetVerseQuantumConeAerialHUD.tsx')
const world=read('../src/components/StreetVerseMobileWorld.tsx')
assert.ok(atlas.includes('STREETVERSE_GLOBAL_CITIES'),'Global atlas must source real registered city metadata')
for(const id of ['chicago','lagos','abuja','accra','nairobi','johannesburg','addis-ababa','tokyo'])assert.ok(registry.includes("id:'"+id+"'"),'Registry missing global city '+id)
assert.ok(atlas.includes("city.status==='live-alpha'"),'Accurate live vs building vs planned city labels')
assert.ok(atlas.includes('data-global-enter-chicago'),'Playable Chicago must have local fly-in')
assert.ok(atlas.includes('data-global-preview-only={selected.id}'),'Unbuilt cities must show preview-only, no fake 3D')
assert.ok(atlas.includes('data-global-city={city.id}'),'Globe cities must be selectable')
assert.ok(atlas.includes('projectStreetVerseCityOnGlobe'),'World overview must project marker coordinates')
assert.ok(atlas.includes('minHeight:52'),'One-hand city list targets must be large')
assert.ok(atlas.includes('No satellite tiles, paid map requests'),'No cost-increasing third-party imagery')
assert.ok(cone.includes('data-cone-open-global'),'Local lens must link out to planet view')
assert.ok(world.includes("'tryamm:streetverse-global-cone-open'"),'Global atlas must be launchable from world')
assert.ok(world.includes('onGlobalChicago=()=>{onGlobalConeClose();onConeOpen()}'),'Chicago must hand off to real 3D camera')
assert.ok(world.includes('globalConeActiveRef.current'),'Local renderer must pause while full globe overlay is shown')
assert.ok(world.includes("'🌍 STREETVERSE GLOBAL'"),'Accessible mobile quick-menu path to globe')
assert.ok(world.includes("removeEventListener('tryamm:streetverse-global-cone-open',onGlobalConeOpen)"),'Global event listener must release on unmount')
console.log('STREETVERSE GLOBAL QUANTUM CONE PASS: 22 registry cities, honest status, no paid atlas, globe->Chicago 3D fly-in, accessible return')
