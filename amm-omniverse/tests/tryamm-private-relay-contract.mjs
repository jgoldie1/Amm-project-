import fs from 'node:fs'
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8')
const cfg=JSON.parse(read('config/tryamm-private-relay-release.json'))
const arch=read('src/data/TryammPrivateRelayArchitecture.ts')
const ui=read('src/components/TryammPrivateRelayCenter.tsx')
const must=(ok,msg)=>{if(!ok)throw new Error('TRYAMM PRIVATE RELAY CONTRACT FAIL: '+msg)}
must(cfg.storeReleaseEnabled===false,'VPN must remain release-disabled until native compile/review')
must(cfg.pwa.systemWideVpn===false,'PWA must not claim system-wide VPN')
must(cfg.ios.personalVpnEntitlement==='com.apple.developer.networking.vpn.api','iOS entitlement requirement missing')
must(cfg.ios.explicitUserAuthorization===true,'iOS user authorization requirement missing')
must(cfg.android.vpnServiceRequired===true,'Android VpnService requirement missing')
must(cfg.android.prominentDisclosureAndConsentRequired===true,'Play disclosure/consent requirement missing')
must(cfg.privacy.monetizeVpnTraffic===false,'VPN traffic monetization must remain forbidden')
must(cfg.privacy.edgeEarningsFromVpnTraffic===false,'VPN must not create Edge earnings')
must(arch.includes("earningsBoundary:'VPN usage itself does not create Edge earnings"),'architecture earnings boundary missing')
must(ui.includes('NATIVE TUNNEL NOT YET RELEASE-CERTIFIED'),'UI truth state missing')
must(ui.includes('tunneled traffic is never sold'),'UI privacy boundary missing')
console.log('TRYAMM PRIVATE RELAY CONTRACT PASS: store-safe architecture + truthful native readiness + no traffic monetization')
