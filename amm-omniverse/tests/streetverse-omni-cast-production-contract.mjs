import assert from 'node:assert/strict'
import fs from 'node:fs'
const file=(p)=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8')
const cast=file('src/data/StreetVerseOmniCastProduction.ts')
const family=file('src/game/characters/meetTheStubbsFamilyFriends.ts')
const music=file('src/data/ChicagoMusicLegacyMissionRegistry.ts')
const global=file('src/data/StreetVerseGlobalCharacterRegistry.ts')
const district=file('src/components/MeetTheStubbsWorldDistrict.tsx')
const artists=[...music.matchAll(/id:'([^']+)',displayName:'([^']+)'/g)]
const people=[...family.matchAll(/id:'([^']+)',displayName:'([^']+)'/g)]
const globalCharacters=[...global.matchAll(/id:'([^']+)',displayName:'([^']+)'/g)]
assert.equal(artists.length,33,'Keep all existing Chicago artist references')
assert.equal(people.length,29,'Keep all existing named family/friends')
assert.equal(globalCharacters.length,23,'Keep first-wave fictional global cast')
assert.ok(family.includes('...SOCIAL_CREATOR_PLACEHOLDERS'),'Keep 10 social creator placeholders')
assert.ok(cast.includes('...FAMILY,...MUSIC_HISTORY,...GLOBAL,...ORIGINAL,...GUESTS'),'All source registries must join the new batch')
assert.ok(cast.includes("playableStandIn:false"),'Real artist references must not become unlicensed look-alikes')
assert.ok(cast.includes("likenessRights:'reference-check-required'"),'Rights review must be explicit')
assert.ok(cast.includes("musicRights:'original-or-cleared-only'"),'No free use of artist music')
assert.ok(cast.includes("visualSlot:'none-public-figure'"),'No artist mesh without rights')
assert.ok(cast.includes("character.id==='bj-stubbs'?'owner-v15-priority'"),'BJ owner approval must remain explicit')
assert.ok(cast.includes('STREETVERSE_ORIGINAL_PERFORMERS'),'Independent original artists must be included')
assert.ok(cast.includes('STREETVERSE_MUSIC_GENRES'),'Full music genre lane catalog is required')
assert.ok(global.includes('getAllFirstWaveGlobalCharacterCast'),'Global characters must be available to batch production')
assert.ok(district.includes('REGISTERED_FAMILY_EXTRAS'),'Family members omitted from 3D scene must be added as neutral stand-ins')
