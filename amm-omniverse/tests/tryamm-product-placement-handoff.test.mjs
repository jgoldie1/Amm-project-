import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {createPlacementBrief,placementToInquiryNotes,placementToStudioHandoff,isPlacementBrief,TRYAMM_PLACEMENT_SURFACES,TRYAMM_PLACEMENT_STUDIO_HANDOFF_KEY} from '../src/runtime/TryammPlacementBriefRuntime.ts'
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const valid={
 brand:' TRYAMM <LLC> ',product:'StreetVerse Demo',description:'Chicago storefront product scene.',
 productUrl:'https://example.org/showcase',surfaces:['holo-reel','streetverse-world','omnibox-story'],
 ctaText:'Visit our shop',creativeNotes:'BJ visits a storefront',advertiserAcknowledgesRightsReview:true
}
const brief=createPlacementBrief(valid)
assert.equal(brief.brand,'TRYAMM LLC')
assert.equal(brief.status,'proposal-only')
assert.equal(brief.rights,'unverified')
assert.equal(brief.publicationAuthorized,false)
assert.equal(brief.billingAuthorized,false)
assert.equal(brief.surfaces.length,3)
assert.equal(brief.productUrl,'https://example.org/showcase')
assert.ok(brief.requiredApprovals.some(x=>x.includes('Advertising disclosure')))
assert.ok(isPlacementBrief(brief))
assert.equal(isPlacementBrief({...brief,publicationAuthorized:true}),false)
assert.throws(()=>createPlacementBrief({...valid,productUrl:'javascript:alert(1)'}),/public HTTPS/)
assert.throws(()=>createPlacementBrief({...valid,productUrl:'https://admin:password@example.org/private'}),/public HTTPS/)
assert.throws(()=>createPlacementBrief({...valid,advertiserAcknowledgesRightsReview:false}),/rights/)
assert.throws(()=>createPlacementBrief({...valid,surfaces:[]}),/placement/)
assert.throws(()=>createPlacementBrief({...valid,brand:'X'}),/brand/)
assert.equal(TRYAMM_PLACEMENT_SURFACES.length,5)
const notes=placementToInquiryNotes(brief)
assert.ok(notes.includes('NO PLACEMENT PUBLISHED'))
assert.ok(notes.includes('StreetVerse Demo'))
assert.ok(notes.length<=900)
const studio=placementToStudioHandoff(brief)
assert.equal(studio.creatorMode,'holographic')
assert.ok(studio.projectPrompt.includes('Do not present sponsor assets as cleared'))
assert.equal(studio.source,'tryamm-growth')
assert.equal(TRYAMM_PLACEMENT_STUDIO_HANDOFF_KEY,'tryamm.placement-studio-proposal.v1')
const builder=read('src/components/TryammPlacementBriefBuilder.tsx')
const landing=read('src/components/TryammConnectedGrowthLanding.tsx')
const media=read('src/components/MediaStudioLauncher.tsx')
const omni=read('src/components/OmniBoxStoryStudio.tsx')
assert.ok(builder.includes('onQuote(brief)')&&builder.includes('PREPARE PLACEMENT PROPOSAL'))
assert.ok(builder.includes("tryamm:media-studio-open")&&builder.includes('placementToStudioHandoff(brief)'))
assert.ok(builder.includes('TRYAMM_PLACEMENT_STUDIO_HANDOFF_KEY')&&builder.includes("window.location.href='/omni-box?from=tryamm-placement'"))
assert.ok(builder.includes('tryamm:holo-ads-create-campaign'))
assert.ok(landing.includes('<TryammPlacementBriefBuilder onQuote={acceptPlacementQuote}/>'))
assert.ok(landing.includes('placementToInquiryNotes(brief)')&&landing.includes("setOfferId('product-placement')"))
assert.ok(media.includes('if(detail?.projectPrompt)setProjectPrompt')&&media.includes('setCreatorMode(detail.creatorMode)'))
assert.ok(omni.includes('isPlacementBrief(brief)')&&omni.includes('IMPORT PLACEMENT INTO ACT 3')&&omni.includes("setSelected(2)"))
assert.ok(!omni.includes('publishPlacement('))
console.log('TRYAMM Holo product-placement review, Reel, OmniBox and lead handoff PASS')
