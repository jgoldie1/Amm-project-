import assert from 'node:assert/strict'
import fs from 'node:fs'
import{
 createDominion,normalizeDominion,selectDistrict,playMission,buildCity,dominionMetrics,
 BUILDS,MISSIONS,DISTRICTS,
}from '../src/runtime/StreetVerseDistrictDominionEngine.ts'

const read=file=>fs.readFileSync(new URL('../'+file,import.meta.url),'utf8')
const engine=read('src/runtime/StreetVerseDistrictDominionEngine.ts')
const ui=read('src/components/StreetVerseDistrictDominionPanel.tsx')
const entrance=read('src/components/StreetVerseGeoSpawnBridge.tsx')
const safeWorld=read('src/components/StreetVerseSafeWorld.tsx')
const launcher=read('src/components/StreetVerseDominionLauncher.tsx')
const safeEntry=read('src/streetverse-safe.tsx')
let s=createDominion()
assert.equal(s.mode,'LOCAL_DEMO')
assert.equal(s.districts.length,3)
assert.equal(s.credits,300)
assert.equal(s.district,'circle-park')
assert.equal(MISSIONS.length,4)
assert.equal(BUILDS.length,6)
assert.equal(DISTRICTS.length,3)
assert.equal(dominionMetrics(s).realMoney,0)
assert.equal(dominionMetrics(s).ranked,false)
assert.equal(dominionMetrics(s).verifiedOnlineWins,0)
assert.equal(playMission(s,'invalid'),s,'unknown missions cannot mutate state')
s=playMission(s,'creator-pk')
assert.equal(s.credits,358)
assert.equal(s.xp,95)
assert.equal(s.districts[0].influence,53)
s=playMission(s,'race')
assert.equal(s.districts[0].owner,'west-side-creators','capture after enough influence')
assert(s.history.length>0)
const after3=playMission(s,'community')
assert(after3.districts[0].rivalInfluence>0,'fictional AI counterplay must exist')
assert.equal(after3.districts[0].rounds,3)
const built=buildCity(after3,'park')
assert.equal(built.credits,after3.credits-90)
assert(built.districts[0].buildings.includes('park'))
assert.equal(buildCity(built,'park'),built,'duplicates cannot charge twice')
assert.equal(buildCity({...built,credits:0},'housing').credits,0,'no negative account balances')
const second=selectDistrict(built,'taylor-street')
assert.equal(second.district,'taylor-street')
assert.equal(second.districts[1].owner,'neutral')
assert.equal(selectDistrict(second,'not-a-district'),second)
assert.equal(second.districts[0].buildings[0],'park','district data preserved when traveling')
const forged=normalizeDominion({...second,mode:'RANKED',credits:1e20,xp:-999,
 districts:second.districts.map(d=>({...d,owner:'hacked',happiness:999,buildings:['studio','hack','studio']})),
 history:[{key:1,district:'circle-park',message:'x'.repeat(600)}]})
assert.equal(forged.mode,'LOCAL_DEMO')
assert.equal(forged.credits,100000)
assert.equal(forged.xp,0)
assert.equal(forged.districts[0].owner,'neutral')
assert.equal(forged.districts[0].happiness,100)
assert.deepEqual(forged.districts[0].buildings,['studio'])
assert.equal(forged.history[0].message.length,150)
assert.match(engine,/verifiedOnlineWins:0,realMoney:0,ranked:false/)
assert.doesNotMatch(engine,/\bfetch\s*\(/,'simulation must not call external services')
assert.doesNotMatch(engine,/getSupabaseClient\s*\(|createClient\s*\(|\bstripe\s*\.|MediaRecorder\s*\(|payableBalance\s*=/i,'simulation cannot invoke providers or settle payments')
assert(entrance.includes('StreetVerseDominionLauncher'),'3D world must mount shared launcher')
assert(safeWorld.includes('StreetVerseMobilePlayableWorld'),'safe world must keep HTML play')
assert(safeEntry.includes('StreetVerseDominionLauncher'),'standalone safe entry must expose District Dominion')
assert(entrance.includes('showRestore3D={explicitSafe}'),'automatic recovery must not duplicate 3D retry')
assert(entrance.includes('StreetVerseDominionLauncher'),'main 3D and recovery entry must expose District Dominion')
const westSide=read('src/runtime/StreetVerseWestSideVisibleWorldRuntime.ts')
const mobileWorld=read('src/components/StreetVerseMobileWorld.tsx')
assert(westSide.includes('const trackZ=-35')&&westSide.includes('west-side-el-station-platform'),'West Side elevated geometry must line up with existing train')
assert(mobileWorld.includes('train.position.set(-70,7.3,-35)'),'preserve original moving L train')
for(const token of ['StreetVerseDistrictDominionPanel','data-streetverse-dominion-launch','setOpen(true)'])assert(launcher.includes(token))
assert(ui.includes('role="dialog"'))
assert(ui.includes('aria-label="Close District Dominion and return to 3D StreetVerse"'))
assert(ui.includes('aria-label="District influence meters"'))
assert(ui.includes('style={{...button'))
assert(ui.includes('DistrictArtwork'))
assert(ui.includes('buildCity(state,id)'))
assert(ui.includes('playMission(state,id)'))
assert(ui.includes('no real turf ownership'))
assert.doesNotMatch(ui,/new THREE\.WebGLRenderer|new WebGLRenderer/,'no second GPU context on iPhone')
console.log('STREETVERSE DISTRICT DOMINION PASS: 3 districts, original art, one-hand launcher in both worlds, save, build and capture, anti-money safety')
