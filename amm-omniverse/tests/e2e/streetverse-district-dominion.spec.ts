import {test,expect} from '@playwright/test'

test.use({viewport:{width:390,height:844},deviceScaleFactor:2,isMobile:true,hasTouch:true})
test('safe StreetVerse -> District Dominion -> turf win and civic construction -> persists',async({page})=>{
 test.setTimeout(95000)
 await page.goto('/streetverse?mode=safe',{waitUntil:'domcontentloaded',timeout:30000})
 const launcher=page.getByRole('button',{name:'Open District Dominion turf and city builder'})
 await expect(launcher).toBeVisible({timeout:30000})
 await launcher.click()
 const dialog=page.getByRole('dialog',{name:'StreetVerse District Dominion'})
 await expect(dialog).toBeVisible({timeout:25000})
 await expect(dialog.getByRole('heading',{name:'District Dominion'})).toBeVisible()
 await expect(dialog.getByRole('img',{name:/Illustrated Chicago district concept/})).toBeVisible()
 await dialog.getByRole('button',{name:/PK Talent Showcase/}).click()
 await expect(dialog.getByRole('progressbar',{name:'Your crew influence'})).toHaveAttribute('aria-valuenow','53')
 await dialog.getByRole('button',{name:/Chicago Street Circuit/}).click()
 await expect(dialog.getByText(/Current owner:/)).toContainText('West Side Creators')
 await dialog.getByRole('button',{name:'🏗 BUILD CITY'}).click()
 await dialog.getByRole('button',{name:/Community Park/}).click()
 await expect(dialog.getByText('BUILT',{exact:true})).toBeVisible()
 await page.reload({waitUntil:'domcontentloaded'})
 await page.getByRole('button',{name:'Open District Dominion turf and city builder'}).click()
 const restored=page.getByRole('dialog',{name:'StreetVerse District Dominion'})
 await expect(restored.getByText(/Current owner:/)).toContainText('West Side Creators')
 await restored.getByRole('button',{name:'🏗 BUILD CITY'}).click()
 await expect(restored.getByText('BUILT',{exact:true})).toBeVisible()
 await restored.getByRole('button',{name:'Close District Dominion and return to 3D StreetVerse'}).click()
 await expect(page.getByRole('dialog',{name:'StreetVerse District Dominion'})).toHaveCount(0)
})
