import {test,expect} from '@playwright/test'
test('all 60 websites display on the catalog without requiring sign in',async({page})=>{
 await page.goto('/business-app.html')
 await expect(page.getByRole('heading',{name:/Build a business/})).toBeVisible()
 await expect(page.locator('#business-catalog .catalog-card')).toHaveCount(60)
 await expect(page.locator('#business-catalog a[href*="/site-demo.html?template="]')).toHaveCount(60)
 await expect(page.locator('#funding-hub')).toBeVisible()
 await expect(page.locator('canvas')).toHaveCount(0)
})
test('Beautyverse leads to a complete hair salon site with logo and services',async({page})=>{
 await page.goto('/site-demo.html?template=01')
 await expect(page.locator('.full-beauty-links')).toBeVisible()
 await page.locator('.full-beauty-links a[href*="template=55"]').click()
 await expect(page).toHaveURL(/template=55/)
 await expect(page.getByRole('heading',{name:/Style with confidence/})).toBeVisible()
 await expect(page.locator('svg[aria-label*="original animated sample logo"]')).toBeVisible()
 await expect(page.locator('.full-card')).toHaveCount(3)
 await expect(page.locator('.full-form form')).toBeVisible()
})
test('new templates include complete pages and sample e-commerce interaction',async({page})=>{
 for(const id of ['56','57','58','59','60']){
  await page.goto('/site-demo.html?template='+id)
  await expect(page.locator('.full-site')).toBeVisible()
  await expect(page.locator('.full-card')).toHaveCount(3)
  await expect(page.locator('.full-footer')).toBeVisible()
 }
 await page.goto('/site-demo.html?template=58')
 await page.locator('.full-card button').first().click()
 await expect(page.locator('.full-bag')).toContainText('1 items')
 await page.locator('.full-bag button').last().click()
 await expect(page.locator('[role=status]')).toContainText('Demo checkout only')
})
test('Omni Box previews an interactive six-scene storyboard and opens Holo Drama',async({page})=>{
 await page.goto('/omni-box')
 await expect(page.getByRole('heading',{name:'Preview your episode scenes'})).toBeVisible()
 await expect(page.locator('.omni-board-explainer')).toContainText('Scene 1 of 6')
 await page.getByRole('button',{name:'Next scene →'}).click()
 await expect(page.locator('.omni-board-explainer')).toContainText('Scene 2 of 6')
 await page.getByRole('button',{name:'▶ Play storyboard'}).click()
 await expect(page.getByRole('button',{name:'Pause storyboard'})).toBeVisible()
 await page.getByRole('button',{name:'Pause storyboard'}).click()
 await page.getByRole('button',{name:'SEND OUTLINE TO HOLO DRAMA →'}).click()
 await expect(page).toHaveURL(/holo-drama\?from=omni-box/)
})
