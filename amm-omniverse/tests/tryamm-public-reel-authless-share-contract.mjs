import assert from 'node:assert/strict'
import fs from 'node:fs'
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8')
const api=read('api/media/publication.js')
const ui=read('src/components/PublicReelPage.tsx')
const pkg=JSON.parse(read('package.json'))
const s=api.indexOf('let lookupOwner=null;'),auth=api.indexOf('const user=await requireUser(req,res)'),end=api.indexOf('const query=')
assert(s>=0&&auth>s&&end>auth,'auth only gates ID lookups, not public share slugs')
assert(api.includes("if(!slug){"),'raw ID requires authentication')
assert(api.includes("publication.owner_id!==lookupOwner"),'raw ID requires ownership')
assert(api.includes("status:'eq.delivered'"))
assert(api.includes("moderation_status:'in.(approved,restored)'"))
assert(api.includes("media.processing_status!=='ready'"))
assert(api.includes("isProtectedPrivateMedia(media)"))
assert(api.includes("!RIGHTS.has(media.rights_status)"))
assert(api.includes('const publicPublication={'),'response is minimal allowlist')
assert(!api.includes('publication,media:{id:'),'do not return owner/user or internal publication columns')
assert(!ui.includes('getAccessToken'),'public approved Reels must work without login')
assert(ui.includes("cache:'no-store'"))
assert(ui.includes('navigator.share'),'keep mobile share')
assert(pkg.scripts.build.includes('tryamm-public-reel-authless-share-contract.mjs'))
console.log('TRYAMM PUBLIC REEL SHARE PASS: approved published videos available without signup, ID remains owner-gated, private content excluded')
