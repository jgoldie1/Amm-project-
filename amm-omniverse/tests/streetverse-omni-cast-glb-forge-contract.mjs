import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import {spawnSync} from 'node:child_process'
const project=path.resolve(new URL('..',import.meta.url).pathname)
const script=path.join(project,'scripts','forge-streetverse-ensemble.mjs')
const result=spawnSync(process.execPath,[script],{encoding:'utf8',timeout:20000,maxBuffer:2*1024*1024,cwd:project})
assert.equal(result.status,0,(result.stderr||'')+'\n'+(result.stdout||''))
const report=JSON.parse(result.stdout.trim())
assert.ok(report.generated>=160,'Missing expanded ensemble, including Set Apart Music and new original musicians')
assert.ok(report.genreLanes>=106,'Preserve all 85 music lanes and 21 Set Apart lanes')
assert.equal(report.artistLikenessModels,0)
const folder=path.resolve(project,'..','artifacts','streetverse-omni-cast')
const manifest=JSON.parse(fs.readFileSync(path.join(folder,'ensemble-manifest.json'),'utf8'))
assert.equal(manifest.entries.length,report.generated)
assert.equal(report.generated,manifest.registeredFamily-1+manifest.globalFictional+manifest.originalPerformers)
assert.ok(manifest.originalPerformers>=106,'One genre avatar each plus additional original named roles')
assert.equal(manifest.originalNamedMusicians,26)
assert.equal(manifest.setApartNamedMusicians,21)
assert.equal(new Set(manifest.entries.filter(entry=>entry.lane==='original-performer').map(entry=>entry.genre)).size,manifest.musicGenreLanes.length)
assert.equal(manifest.musicGenreLanes.length,106)
assert.equal(manifest.artistHistoryModelsGenerated,0)
assert.equal(manifest.musicRecordingsGenerated,0)
for(const row of manifest.entries){
 const buffer=fs.readFileSync(path.join(folder,row.file))
 assert.equal(buffer.readUInt32LE(0),0x46546c67)
 assert.equal(buffer.readUInt32LE(4),2)
 assert.equal(buffer.readUInt32LE(8),buffer.length)
 assert.equal(buffer.readUInt32LE(16),0x4e4f534a)
 const length=buffer.readUInt32LE(12)
 const json=JSON.parse(buffer.subarray(20,20+length).toString())
 assert.equal(json.meshes.length,6)
 assert.equal(json.animations.length,7)
 assert.deepEqual(json.animations.map(a=>a.name),['SV_Idle','SV_Walk','SV_Run','SV_Driving_Arms','SV_Talk','SV_Nod','SV_Dance'])
 assert.equal(json.extras.sourceGenerator,'TRYAMM-Original-Character-Studio')
 assert.equal(json.extras.originalGeometry,true)
 assert.equal(json.extras.noExternalCharacterAssets,true)
 assert.ok(json.nodes.some(node=>node.name==='Head'))
 assert.ok(json.extras.prototype)
 assert.equal(json.extras.likenessCertified,false)
 assert.ok(!row.file.toLowerCase().includes('king-von')&&!row.file.toLowerCase().includes('twista')&&!row.file.toLowerCase().includes('michael-jackson'))
}
console.log('PASS: generated '+manifest.entries.length+' TRYAMM-original neutral GLBs, seven demo animation clips, '+manifest.musicGenreLanes.length+' genre lanes and no real-artist likenesses or recordings')
