import fs from 'node:fs'
import assert from 'node:assert/strict'
import {
 STAR_FORMATS,STAR_DISTRIBUTION,newStarTalentDraft,updateStarTalentDraft,
 readyForStarHumanReview,prepareStarTalentReview,starProductionPlan,starBillboardPreview,
} from '../src/runtime/StarVerseNetworkPipeline.ts'

const read=(p)=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8')
const runtime=read('src/runtime/StarVerseNetworkPipeline.ts')
const studio=read('src/components/StarVerseNetworkStudio.tsx')
const network=read('src/components/AllAmericanNetworkHub.tsx')
const main=read('src/main.tsx')
const starStudio=read('src/components/StarStudioCenter.tsx')
const pk=read('src/components/PKLivingWorldsArena.tsx')
const control=read('src/components/AllAmericanNetworkControlRoom.tsx')
const tv=read('src/components/OTTIsaiahTV.tsx')
const music=read('src/components/HoloMusicStreaming.tsx')
const movie=read('src/components/MovieStudioCenter.tsx')
const media=read('src/components/MediaStudioLauncher.tsx')

assert.equal(STAR_FORMATS.length,6)
for(const id of ['audition','music','movie','video','pk-special','podcast'])assert(STAR_FORMATS.some(f=>f.id===id),id)
for(const id of ['isaiah-tv','all-american-network','holo-music','holo-drama','free-tv','digital-billboard','streetverse-billboard','reels'])assert(STAR_DISTRIBUTION.some(f=>f.id===id),id)
const blank=newStarTalentDraft()
assert.equal(blank.status,'LOCAL_DRAFT')
assert.equal(readyForStarHumanReview(blank),false)
assert.equal(prepareStarTalentReview(blank).status,'LOCAL_DRAFT')
let content=updateStarTalentDraft(blank,{title:'My Star Show',creatorCredit:'First Star',synopsis:'A creator-led musical audition for Isaiah AI TV',format:'music',
 destinations:['isaiah-tv','digital-billboard','all-american-network'],
 musicRightsAttested:true,visualRightsAttested:true,consentAttested:true})
assert.equal(readyForStarHumanReview(content),true)
assert.equal(prepareStarTalentReview(content).status,'REVIEW_PREPARED')
assert.equal(readyForStarHumanReview(updateStarTalentDraft(content,{audience:'teen'})),false,'youth submissions stay blocked pending guardian backend')
assert.equal(prepareStarTalentReview(updateStarTalentDraft(content,{consentAttested:false})).status,'LOCAL_DRAFT')
const plan=starProductionPlan(content)
assert.equal(plan.canRequestHumanReview,true)
assert.equal(plan.publicDistributionAuthorized,false)
assert.equal(plan.externalStreamingActive,false)
assert.equal(plan.billboardsBooked,false)
assert.equal(plan.payoutsAuthorized,false)
assert(plan.destinationRequests.every(x=>x.ready===false&&x.reviewRequired===true))
const board=starBillboardPreview(content)
assert.equal(board.providerBooked,false)
assert.equal(board.adDeliveryVerified,false)
assert.equal(board.rightsReviewRequired,true)
assert.equal(board.status,'DRAFT')

assert.match(main,/\/network\/talent-studio/)
assert.match(network,/StarVerseNetworkStudio/)
assert.match(network,/AUDITION • MUSIC • MOVIE • BILLBOARD/)
assert.match(starStudio,/START AN AUDITION \/ TV \/ MUSIC \/ MOVIE/)
assert.match(pk,/\/network\/talent-studio\?from=pk/)
assert.match(studio,/readPKStoryDraft/)
assert.match(studio,/writeStarTalentDraft/)
assert.match(studio,/prepareStarTalentReview/)
assert.match(studio,/setPreview\('audio'\)/)
assert.match(studio,/setPreview\('music'\)/)
assert.match(studio,/setPreview\('movie'\)/)
assert.match(studio,/setPreview\('isaiah'\)/)
assert.match(studio,/href="\/reel-creator"/)
assert.match(studio,/href="\/holo-drama"/)
assert.match(studio,/sessionStorage.setItem\('tryamm.starverse.broadcast-handoff.v1'/)
assert.match(control,/sessionStorage.getItem\('tryamm.starverse.broadcast-handoff.v1'/)
assert.match(control,/No broadcast is live, scheduled, licensed or rights-cleared/)
assert.match(tv,/Isaiah AI TV/)
assert.match(music,/is_public/)
assert.match(movie,/120 MIN/)
assert.match(media,/getAccessToken/)
assert.doesNotMatch(runtime,/\b(fetch|axios)\s*\(/,'Local production contract must not silently call providers')
assert.match(runtime,/publicDistributionAuthorized:false/)
assert.match(runtime,/billboardsBooked:false/)
assert.match(runtime,/payoutsAuthorized:false/)
console.log('StarVerse → Isaiah AI TV → All American Network / Holo music, movie, video, billboard draft contract: PASS. Production remains local-preview, not public distribution.')
