import assert from 'node:assert/strict'
import fs from 'node:fs'
import {createChicagoAcceptanceSession} from '../src/runtime/StreetVerseChicagoMotionAcceptance.ts'
const session=createChicagoAcceptanceSession()
assert.throws(()=>session.drive(),/Out-of-order/)
session.walk()
session.enter()
session.drive()
session.exit()
session.talk()
session.complete()
const saved=session.save()
const restored=session.reload(saved.saveData)
assert.equal(restored.credits,100)
assert.equal(restored.missionComplete,true)
assert.equal(restored.inVehicle,false)
assert.equal(restored.events.length,9)
assert.throws(()=>session.complete(),/Out-of-order/)
const record=session.record()
assert.equal(record.passed,true)
assert.equal(record.requiresDeviceVerification,true)
fs.mkdirSync('test-results',{recursive:true})
fs.writeFileSync('test-results/chicago-motion-acceptance.json',JSON.stringify(record,null,2)+'\n')
console.log('CHICAGO MOTION SIMULATION PASS; receipt: test-results/chicago-motion-acceptance.json')
