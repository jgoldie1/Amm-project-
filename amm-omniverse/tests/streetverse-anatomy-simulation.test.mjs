import assert from 'node:assert/strict'
import {createStreetVerseOrganState,applyStreetVerseOrganImpact,resetStreetVerseOrganState} from '../src/runtime/StreetVerseAnatomySimulation.ts'

const bj=createStreetVerseOrganState('bj-stubbs')
assert.equal(bj.integrity.heart,100)
assert.equal(bj.breathing,100)
assert.equal(bj.consciousness,'alert')
assert.equal(bj.fictional,true)
assert.strictEqual(applyStreetVerseOrganImpact(bj,{amount:-10,zone:'chest'}),bj)
assert.strictEqual(applyStreetVerseOrganImpact(bj,{amount:Infinity,zone:'chest'}),bj)
const chest=applyStreetVerseOrganImpact(bj,{amount:25,zone:'chest'})
assert.ok(chest.integrity.heart<100&&chest.integrity.lungs<100)
assert.equal(chest.integrity.brain,100)
assert.ok(chest.breathing<100)
assert.equal(bj.integrity.heart,100,'state updates must not mutate saved profiles')
const head=applyStreetVerseOrganImpact(bj,{amount:100,zone:'head'})
assert.equal(head.consciousness,'downed')
assert.equal(head.needsRescue,true)
const repeated=applyStreetVerseOrganImpact(head,{amount:25,zone:'chest'})
assert.strictEqual(repeated,head,'downed character must not repeatedly lose organ integrity')
const leg=applyStreetVerseOrganImpact(bj,{amount:45,zone:'legs'})
assert.ok(leg.mobility<bj.mobility)
assert.equal(leg.integrity.heart,100)
const healed=resetStreetVerseOrganState('bj-stubbs')
assert.equal(healed.consciousness,'alert')
assert.equal(healed.integrity.brain,100)
assert.equal(healed.mobility,100)
console.log('StreetVerse fictional anatomy state transitions PASS (not medical simulation)')
