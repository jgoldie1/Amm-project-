import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=(file)=>readFileSync(new URL('../'+file,import.meta.url),'utf8')
const tuner=read('src/runtime/StreetVerseVehicleNetworkTuner.ts')
const ui=read('src/components/StreetVerseVehicleTelevisionTuner.tsx')
const lab=read('src/components/StreetVerseTransportScreenLab.tsx')
const freeTv=read('src/runtime/FreeTvCommercialRuntime.ts')
const broadcast=read('src/runtime/TryammBroadcastOSRuntime.ts')
const radio=read('src/runtime/VerseRadioRuntime.ts')
const main=read('src/main.tsx')
const channelIds=['all-american-network','free-tv','holoverse-tv','faithverse-tv','isaiah-ai-tv','starverse-live','who-wants-to-be-a-star','servants-of-christ-network','streetverse-local-tv']
for(const id of channelIds)assert.ok(tuner.includes("id:'"+id+"'"),'missing TV channel '+id)
assert.ok(tuner.includes("route:'/free-tv'"),'free TV must use already existing route')
assert.ok(main.includes("'/free-tv'"),'free TV route must be registered in main')
assert.ok(tuner.includes("kind:'programming-slot'"),'unverified verse TV channels must be marked as programming slots')
assert.ok(tuner.includes("isActualPlayback:false"),'listing must not pretend to be a verified stream')
assert.ok(tuner.includes('stepVehicleTvPreset'),'a real channel step function is required')
assert.ok(ui.includes('Previous television channel')&&ui.includes('Next television channel'),'channel dial must have both directions')
assert.ok(ui.includes('STREETVERSE_VEHICLE_TV_PRESETS.map'),'user must be able to pick a specific channel')
assert.ok(ui.includes('currentVehicleTvListing'),'TV channel labels must read existing Broadcast OS feed listing')
assert.ok(ui.includes('tryamm:broadcast-os-state')&&broadcast.includes('tryamm:broadcast-os-state'),'registered broadcast OS state must be observed')
assert.ok(ui.includes('tryamm:verse-radio-pause')&&radio.includes('tryamm:verse-radio-pause'),'TV tuning must avoid radio overlap')
assert.ok(ui.includes('tryamm:free-tv-commercial-plan-request')&&freeTv.includes('tryamm:free-tv-commercial-plan-request'),'Free TV ad preview must use original scheduling engine')
assert.ok(ui.includes('viewerPriceUsd===0'),'Free TV remains free to viewer')
assert.ok(ui.includes('Playback has not started'),'commercial planning must not invent advertising playback')
assert.ok(!ui.includes('new Audio(')&&!ui.includes('new Hls('),'do not duplicate audio and streaming engines')
assert.ok(lab.includes('<StreetVerseVehicleTelevisionTuner/>'),'TV dial must be in the in-game transport studio')
assert.ok(lab.includes('VERSE_RADIO_STATIONS.map'),'retain existing radio channel switching')
console.log('StreetVerse Free TV + all existing network channel dial contract PASS')
