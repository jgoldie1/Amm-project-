import assert from 'node:assert/strict'
import fs from 'node:fs'
import {ABLA_TOUR_STOPS,createABLATour,startABLATour,nextABLATourStop,advanceABLATour,normalizeABLATour} from '../src/runtime/StreetVerseABLANeighborhoodTour.ts'

const read=name=>fs.readFileSync(new URL('../'+name,import.meta.url),'utf8')
const game=read('src/components/StreetVerseMobileWorld.tsx')
const builder=read('src/components/StreetVerseWestSideWorldBuilder.tsx')
const hud=read('src/components/StreetVerseABLANeighborhoodTourHUD.tsx')
const source=read('src/runtime/StreetVerseABLANeighborhoodTour.ts')
const safe=read('src/components/StreetVerseMobilePlayableWorld.tsx')
assert.equal(ABLA_TOUR_STOPS.length,5)
assert.equal(ABLA_TOUR_STOPS[0].id,'circle-park-1111-laflin')
assert.equal(ABLA_TOUR_STOPS.at(-1).id,'abla-new-homes')
let state=createABLATour()
assert.equal(state.status,'idle')
assert.equal(nextABLATourStop(state),null)
state=startABLATour()
assert.equal(state.status,'active')
assert.equal(advanceABLATour(state,999,999),state,'cannot complete stop from far away')
assert.equal(advanceABLATour(state,NaN,0),state,'invalid coordinates cannot advance')
for(const stop of ABLA_TOUR_STOPS){
 assert.equal(nextABLATourStop(state)?.id,stop.id)
 state=advanceABLATour(state,stop.x,stop.z)
 assert(state.visited.includes(stop.id))
}
assert.equal(state.status,'complete')
assert.equal(state.nextIndex,5)
assert.equal(nextABLATourStop(state),null)
assert.equal(advanceABLATour(state,0,0),state,'completed tour cannot repeat rewards')
assert.equal(normalizeABLATour({...state,mode:'REAL_MONEY'}).status,'idle','forged monetary tour rejected')
assert.equal(normalizeABLATour({...state,visited:['abla-new-homes']}).nextIndex,0,'out of order checkpoints rejected')
assert(game.includes('<StreetVerseABLANeighborhoodTourHUD/>'),'tour HUD must be mounted in real 3D playable world')
assert(builder.includes('tryamm:abla-neighborhood-tour-start'),'World Builder must start the existing playable tour')
assert(builder.includes('Start Circle Park Taylor Laflin ABLA neighborhood trail'),'one-hand tour button accessible')
assert(hud.includes('tryamm:streetverse-player-position'),'actual player movement must advance trail')
assert(hud.includes('tryamm:west-side-route-request'),'fast travel must use existing in-world route')
assert(!safe.includes('StreetVerseABLANeighborhoodTourHUD'),'do not add 3D HUD to fallback HTML city')
for(const token of ['LOCAL_EXPLORATION','ABLA_TOUR_KEY'])assert(source.includes(token))
assert.doesNotMatch(source,/\bfetch\s*\(|\bstripe\b|payableBalance|earnCash/i,'local tour cannot award verified economy')
console.log('ABLA NEIGHBORHOOD TRAIL PASS: five ordered walk checkpoints, player-position progress, local-only save, accessible UI, safe fallback isolation')
