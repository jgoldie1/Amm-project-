import assert from 'node:assert/strict'
import fs from 'node:fs'
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8')
const world=read('src/components/StreetVerseMobileWorld.tsx')
const shops=read('src/runtime/StreetVerseLivingStoreScene.ts')
const mission=read('src/runtime/StreetVerseHoloDeliveryMissionRuntime.ts')
const missionHud=read('src/components/StreetVerseHoloDeliveryMissionHUD.tsx')
const shopping=read('src/runtime/StreetVerseShoppingLedger.ts')
assert.match(shops,/export function storeInteriorCollision/)
assert.match(world,/storeInteriorCollision\(x,z\)/)
assert.match(world,/deliveryParcel\.visible=/)
// Parcel attachment is centralized: the same mesh moves between the hero, van
// and recipient. Test all three transitions instead of an obsolete direct add/remove.
assert.match(world,/const attachParcel=\(target:THREE\.Object3D[^\n]*target\.add\(deliveryParcel\)/)
assert.match(world,/attachParcel\(avatar,\.55,1\.1,\.3\)/)
assert.match(world,/nextParent==='van'[^\n]*attachParcel\(holoDeliveryVan/)
assert.match(world,/nextParent==='vendor'[^\n]*attachParcel\(vendorParcelAnchor/)
assert.match(world,/else attachParcel\(avatar,\.55,1\.1,\.3\)/)
assert.match(world,/deliveryParcel\.visible=parcelStage==='drive'\|\|parcelStage==='handoff'\|\|parcelStage==='complete'/)
assert.match(world,/window\.addEventListener\('tryamm:streetverse-package-stage',onParcelStage\)/)
assert.match(world,/window\.removeEventListener\('tryamm:streetverse-package-stage',onParcelStage\)/)
assert.match(mission,/!mission\.arrived/)
assert.match(missionHud,/SAVE_KEY/)
assert.match(missionHud,/tryamm:streetverse-package-stage/)
assert.match(shopping,/completedMissionIds\.includes\(id\)/)
assert.match(shopping,/SHOPPING_SAVE_KEY/)
console.log('Chicago storefront collision, package visual and persisted delivery bridge contract PASS')
