const cfg=JSON.parse(fs.readFileSync(new URL('../config/private-relay-release.json',import.meta.url),'utf8'))
const arch=fs.readFileSync(new URL('../src/data/TryammPrivateRelayArchitecture.ts',import.meta.url),'utf8')
