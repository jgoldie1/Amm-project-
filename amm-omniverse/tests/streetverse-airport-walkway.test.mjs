import assert from 'node:assert/strict'
import {createAirportWalkway,boardWalkway,leaveWalkway,setWalkwayRunning,setWalkwayDirection,emergencyStopWalkway,resetWalkway,tickAirportWalkway} from '../src/runtime/StreetVerseAirportWalkwayRuntime.ts'
let s=createAirportWalkway('terminal-a',24)
assert.equal(s.accessibleAlternateAvailable,true)
assert.equal(s.simulationOnly,true)
s=setWalkwayRunning(s,true)
s=boardWalkway(s,'passenger-1')
assert.equal(Object.keys(s.riders).length,1)
assert.strictEqual(setWalkwayDirection(s,-1),s,'cannot reverse while running or occupied')
s=tickAirportWalkway(s,.1)
assert.ok(s.riders['passenger-1'].distanceM>0,'moving walkway advances passenger')
assert.strictEqual(tickAirportWalkway(s,Infinity),s,'invalid dt is ignored')
s=emergencyStopWalkway(s)
assert.equal(s.enabled,false)
assert.strictEqual(setWalkwayRunning(s,true),s,'emergency stop remains engaged')
const atStop=tickAirportWalkway(s,.1)
assert.equal(atStop.riders['passenger-1'].distanceM,s.riders['passenger-1'].distanceM)
assert.strictEqual(resetWalkway(s),s,'occupied walkway cannot reset emergency stop')
s=leaveWalkway(s,'passenger-1')
s=resetWalkway(s)
assert.equal(s.emergencyStopped,false)
s=setWalkwayDirection(s,-1)
assert.equal(s.direction,-1)
s=boardWalkway(s,'passenger-2')
assert.equal(s.riders['passenger-2'].distanceM,s.lengthM)
console.log('StreetVerse airport moving walkway simulation PASS')
