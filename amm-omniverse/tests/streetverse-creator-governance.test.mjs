import assert from 'node:assert/strict'
import {createProposal,castCreatorVote,closeCreatorVote,authorizeCreatorProposal,GOVERNANCE_POLICY,CREATOR_GOVERNANCE_RIGHTS} from '../src/runtime/StreetVerseCreatorGovernance.ts'
const eligible=new Set(['a','b','c','d','e','f'])
let p=createProposal('access-001','creator-a','accessibility','Improve large buttons','Fund an accessibility controls design review','2026-11-15')
for(const id of ['a','b','c','d'])p=castCreatorVote(p,id,'yes',eligible)
p=castCreatorVote(p,'e','no',eligible)
assert.throws(()=>castCreatorVote(p,'e','yes',eligible),/Duplicate/)
assert.throws(()=>castCreatorVote(p,'outsider','yes',eligible),/eligible/)
p=closeCreatorVote(p,'2026-11-16')
assert.equal(p.status,'approved-for-review')
assert.equal(p.authorizedBy,undefined)
assert.throws(()=>authorizeCreatorProposal(p,'',''),/authorization/)
const authorized=authorizeCreatorProposal(p,'tryamm-admin','audit-001')
assert.equal(authorized.status,'executed')
assert.equal(GOVERNANCE_POLICY.treasuryAutospend,false)
assert.equal(CREATOR_GOVERNANCE_RIGHTS.companyEquityGranted,false)
let failed=createProposal('tools-001','creator-a','creator-tools','Improve clothing editor','Allow creators to preview jackets more easily','2026-11-15')
failed=castCreatorVote(failed,'a','yes',eligible)
assert.equal(closeCreatorVote(failed,'2026-11-16').status,'rejected')
console.log('Creator governance vote, quorum, authorization and ownership safeguards PASS')
