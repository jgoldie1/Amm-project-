import fs from 'node:fs'
import assert from 'node:assert/strict'
const read=(name)=>fs.readFileSync(new URL('../src/runtime/'+name,import.meta.url),'utf8')
const shared=read('StreetVerseSharedCastMedicalRuntime.ts')
const cast=read('StreetVerseRecoveredCastRuntime.ts')
const anatomy=read('StreetVerseBJAnatomyRuntime.ts')
const injury=read('StreetVerseBJInjuryBridgeRuntime.ts')
const reaction=read('StreetVerseBJInjuryReactionRuntime.ts')
for(const id of ['bj-stubbs','jacobie-stubbs','lateasia-monroe'])assert.match(shared,new RegExp(id),'All three characters must be recognized: '+id)
for(const kind of ['shot','stab','blunt','fall','recovery','hospital-discharge'])assert.ok(shared.includes("'"+kind+"'"),'Missing shared action '+kind)
for(const organ of ['heart','left-lung','right-lung','liver','stomach','left-kidney','right-kidney'])assert.ok(anatomy.includes("name:'"+organ+"'"),'Missing original organ '+organ)
assert.match(shared,/applyBJInjury\(previous,detail\.kind!\)/,'Shared cast must use existing injury reducer')
assert.match(shared,/createBJInjuryReaction\(\)/,'Shared cast must use existing reactions')
assert.match(shared,/installStreetVerseBJAnatomy\(object\)/,'Shared cast must reuse owner-created organs')
assert.match(shared,/tryamm:streetverse-bj-injury/,'BJ must keep authoritative existing injury runtime')
assert.match(shared,/tryamm:streetverse-cast-rescue-request/,'Severe conditions must notify rescue')
assert.match(shared,/tryamm:streetverse-cast-medical-status/,'Health and view state must be inspectable')
assert.match(shared,/setVisible\(false\)/,'Organs must not appear in ordinary gameplay')
assert.match(shared,/tryamm:streetverse-cast-anatomy-mode/,'Organ view must be opt-in')
assert.match(cast,/medical\.register\(STREETVERSE_RECOVERED_CAST\[role\]\.id,character\.root\)/,'Both companion GLBs must have medical systems')
assert.match(cast,/medical\.tick\(nowMs\)/,'All injuries and organ overlays must tick')
assert.match(cast,/medical\.dispose\(\)/,'Cleanup must remove listeners and organ meshes')
assert.match(injury,/health=Math\.max\(0,Math\.min\(100,/,'Health must be bounded')
assert.match(reaction,/state\.health<=40&&!rescueSent/,'Rescue threshold must be preserved')
console.log('Universal non-graphic injury and seven-organ overlay contracts PASS')
