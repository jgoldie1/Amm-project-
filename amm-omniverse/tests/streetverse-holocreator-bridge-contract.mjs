import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
const read=name=>fs.readFileSync(new URL('../src/'+name,import.meta.url),'utf8')
test('OmniBox keeps six original 5-minute script beats, and adds the new bridge',()=>{
 const omni=read('components/OmniBoxStoryStudio.tsx')
 const main=read('main.tsx')
 assert.match(main,/const MediaStudioLauncher=lazy/)
 assert.match(main,/else if\(isOmniBox\)routeContent=<>/)
 assert.match(main,/<MediaStudioLauncher \/>/)
 assert.equal((omni.match(/durationSeconds:300/g)||[]).length,6)
 assert.match(omni,/import HoloCreatorBridgePanel/)
 assert.match(omni,/onApply=\{text=>changeScene\('dialogue',text\)\}/)
 assert.match(omni,/setRenderedSeconds\(seconds\)/)
 assert.match(omni,/not a complete 30-minute cinematic movie/)
})
test('Holo creator interface is opt-in, offline fallback and creator-approved',()=>{
 const panel=read('components/HoloCreatorBridgePanel.tsx')
 assert.match(panel,/api\/ai\/answer/)
 assert.match(panel,/getAccessToken/)
 assert.match(panel,/Generative provider unavailable/)
 assert.match(panel,/setSuggested\(\{text:fallback/)
 assert.match(panel,/APPLY TO ACT/)
 for(const choice of ['A','B','C','D'])assert.match(panel,new RegExp(choice+":'"))
 assert.match(panel,/No celebrity impersonation/)
})
test('Real short video export uses browser encoder and provides a download',()=>{
 const panel=read('components/HoloCreatorBridgePanel.tsx')
 assert.match(panel,/canvas\.captureStream\(20\)/)
 assert.match(panel,/new MediaRecorder\(stream/)
 assert.match(panel,/new Blob\(chunks/)
 assert.match(panel,/download=\{video\.fileName\}/)
 assert.match(panel,/18-SECOND MOVIE CLIP/)
 assert.match(panel,/not a finished 3D film/i)
})
test('HoloBox handoff imports the actual video blob into existing media studio',()=>{
 const panel=read('components/HoloCreatorBridgePanel.tsx')
 const media=read('components/MediaStudioLauncher.tsx')
 assert.match(panel,/tryamm:media-studio-open/)
 assert.match(panel,/blob:video\.blob/)
 assert.match(media,/detail\.blob instanceof Blob/)
 assert.match(media,/setMediaBlob\(incoming\)/)
 assert.match(media,/setTab\('compose'\)/)
 assert.match(media,/getAccessToken/)
 assert.match(media,/\/api\/media\/upload-intent/)
 assert.doesNotMatch(panel,/\/api\/media\/publish|\/api\/checkout|payableBalance\s*\+=/)
})

