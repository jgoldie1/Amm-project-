import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
const read=(file)=>fs.readFileSync(new URL('../'+file,import.meta.url),'utf8')
test('the World Builder uses existing native assets and reports actual attachment evidence',()=>{
 const builder=read('src/components/StreetVerseWestSideWorldBuilder.tsx')
 const scene=read('src/components/StreetVerseNearWest3D.tsx')
 assert.match(builder,/TRYAMM_NATIVE_RUNTIME_ASSETS/)
 assert.match(builder,/EXISTING TRYAMM FORGE ASSETS/)
 assert.match(builder,/tryamm:streetverse-chicago-native-assets-ready/)
 assert.match(builder,/tryamm:streetverse-west-side-native-assets/)
 assert.match(builder,/tryamm:holoforge-asset-ready/)
 assert.match(builder,/VERIFY 4 GLBs/)
 assert.match(builder,/ENTER TAYLOR 3D/)
 assert.match(builder,/method:'HEAD'/)
 assert.match(scene,/loadTryammNativeCircleParkLayer/)
 assert.match(scene,/tryamm:streetverse-chicago-native-assets-ready/)
})
test('West Side map and mission board open cinematic stories, not beep-only generic mission start',()=>{
 const builder=read('src/components/StreetVerseWestSideWorldBuilder.tsx')
 const director=read('src/components/StreetVerseCinematicMissions.tsx')
 assert.match(builder,/tryamm:streetverse-cinematic-mission-open/)
 assert.doesNotMatch(builder,/new CustomEvent\('tryamm:streetverse-mission-start'/)
 assert.match(director,/hold-the-block/)
 assert.match(director,/business-on-the-block/)
 assert.match(director,/first-ride-story/)
})
test('Taylor button opens the existing 3D renderer and preserves Safe Mode',()=>{
 const builder=read('src/components/StreetVerseWestSideWorldBuilder.tsx')
 const bridge=read('src/components/StreetVerseGeoSpawnBridge.tsx')
 assert.match(builder,/new CustomEvent\('tryamm:west-side-route-request'/)
 assert.match(read('src/components/StreetVerseMobileWorld.tsx'),/addEventListener\('tryamm:west-side-route-request'/)
 assert.match(bridge,/if\(safe\)/)
 assert.match(bridge,/setNearWestOpen\(true\)/)
})
test('existing native asset kit is produced before production build with no Meshy API credits',()=>{
 const pkg=JSON.parse(read('package.json'))
 assert.match(pkg.scripts['assets:prebuild'],/native:assets/)
 assert.match(pkg.scripts.build,/assets:prebuild/)
 const native=read('scripts/tryamm-native-asset-foundry.mjs')
 assert.match(native,/externalApiRequired:false/)
 assert.match(native,/creditsUsed:0/)
 assert.match(native,/kitArtifacts/)
 const glb=read('src/data/TryammNativeRuntimeAssetCatalog.ts')
 assert.match(glb,/\/generated-assets\/native\/kit\/tree\.glb/)
})
