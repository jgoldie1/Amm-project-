import assert from 'node:assert/strict'
import fs from 'node:fs'
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8')
const reel=read('src/components/StreetVerseReelRecorder.tsx')
const security=read('api/_lib/security.js')
const upload=read('api/media/upload-intent.js')
const pub=read('api/media/publish.js')
const deliver=read('api/media/process-publish.js')
const pkg=JSON.parse(read('package.json'))
assert(reel.includes("import {getAccessToken}"),'real auth required before upload')
assert(reel.includes("const bearer=await getAccessToken()"))
assert(reel.includes('headers:authHeaders,body:JSON.stringify({fileName'),'intent bearer')
assert(reel.includes('headers:authHeaders,body:JSON.stringify({mediaId:intentBody.media.id})'),'completion bearer')
assert(reel.includes("headers:authHeaders,body:JSON.stringify({mediaId:intentBody.media.id,destinations:"),'publish bearer')
assert(security.includes("if(!auth.startsWith('Bearer '))"))
assert(reel.includes("tryamm:streetverse-reel-queued"),'queued is not delivered')
assert(!reel.includes("tryamm:streetverse-reel-published"),'cannot announce public delivery before moderation')
assert(reel.includes('public:false'))
assert(reel.includes('NOT public yet'))
assert(reel.includes('UPLOAD TO TRYAMM'))
assert(upload.includes("moderation_status:'pending'"))
assert(pub.includes("status,moderation_status:'pending'"))
assert(deliver.includes("['approved','restored']"),'delivery must remain moderated')
assert(pkg.scripts.build.includes('streetverse-reel-auth-publication-integrity-contract.mjs'))
console.log('STREETVERSE REEL AUTH/PUBLICATION PASS: bearer upload, moderation queue, no false public event')
