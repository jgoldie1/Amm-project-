import {useEffect,useState} from 'react'
import type {BroadcastFeed,BroadcastOSState} from '../runtime/TryammBroadcastOSRuntime'
import type {FreeTvCommercialPlan} from '../runtime/FreeTvCommercialRuntime'
import {STREETVERSE_VEHICLE_TV_PRESETS,currentVehicleTvListing,findVehicleTvPreset,stepVehicleTvPreset,type VehicleTvPresetId} from '../runtime/StreetVerseVehicleNetworkTuner'

const control:React.CSSProperties={minHeight:44,padding:'9px 10px',borderRadius:9,border:'1px solid #52718d',background:'#152e3b',color:'#f5fcff',fontSize:12,touchAction:'manipulation'}

export default function StreetVerseVehicleTelevisionTuner(){
 const [presetId,setPresetId]=useState<VehicleTvPresetId>('all-american-network')
 const [feeds,setFeeds]=useState<BroadcastFeed[]>([])
 const [freeTvPlan,setFreeTvPlan]=useState<FreeTvCommercialPlan|null>(null)
 useEffect(()=>{
  const onBroadcast=(event:Event)=>{
   const state=(event as CustomEvent<BroadcastOSState>).detail
   if(state&&Array.isArray(state.activeFeeds))setFeeds(state.activeFeeds)
  }
  const onFreeTvPlan=(event:Event)=>{
   const plan=(event as CustomEvent<FreeTvCommercialPlan>).detail
   if(plan?.freeAdSupported&&plan.viewerPriceUsd===0)setFreeTvPlan(plan)
  }
  window.addEventListener('tryamm:broadcast-os-state',onBroadcast)
  window.addEventListener('tryamm:free-tv-commercial-plan',onFreeTvPlan)
  window.dispatchEvent(new Event('tryamm:broadcast-os-request'))
  return()=>{
   window.removeEventListener('tryamm:broadcast-os-state',onBroadcast)
   window.removeEventListener('tryamm:free-tv-commercial-plan',onFreeTvPlan)
  }
 },[])
 const preset=findVehicleTvPreset(presetId)
 const listing=currentVehicleTvListing(preset,feeds)
 const choose=(id:VehicleTvPresetId)=>{
  setPresetId(id);setFreeTvPlan(null)
  // Television and radio share the original player. Do not play both at once.
  window.dispatchEvent(new Event('tryamm:verse-radio-pause'))
  window.dispatchEvent(new Event('tryamm:broadcast-os-request'))
 }
 const change=(direction:-1|1)=>choose(stepVehicleTvPreset(presetId,direction).id)
 const previewFreeTvBreaks=()=>window.dispatchEvent(new CustomEvent('tryamm:free-tv-commercial-plan-request',{detail:{showId:'streetverse-free-tv-preview',showTitle:'TRYAMM Free TV',durationMinutes:30}}))
 return <section aria-label="All American Network and Free TV channel selector" style={{border:'1px solid #446c7e',borderRadius:12,padding:11,marginTop:10,background:'#0b2432'}}>
  <div style={{fontWeight:900,letterSpacing:'.05em',fontSize:12}}>ALL AMERICAN • TV CHANNEL DIAL</div>
  <div role="group" aria-label="Change television channel" style={{display:'flex',alignItems:'center',gap:7,marginTop:9}}>
   <button style={control} aria-label="Previous television channel" onClick={()=>change(-1)}>◀ CH−</button>
   <div style={{flex:1,textAlign:'center'}}>
    <div style={{fontSize:11,color:'#9ee7ff'}}>CH {preset.dial}</div>
    <strong style={{fontSize:14}}>{preset.label}</strong>
   </div>
   <button style={control} aria-label="Next television channel" onClick={()=>change(1)}>CH+ ▶</button>
  </div>
  <label htmlFor="streetverse-tv-channel" style={{display:'block',fontSize:11,margin:'10px 0 5px'}}>Select television network or show</label>
  <select id="streetverse-tv-channel" value={presetId} onChange={e=>choose(e.target.value as VehicleTvPresetId)} style={{...control,width:'100%',background:'#163646'}}>
   {STREETVERSE_VEHICLE_TV_PRESETS.map(p=><option key={p.id} value={p.id}>{p.dial}. {p.label}</option>)}
  </select>
  <div aria-live="polite" style={{padding:'11px',border:'1px solid #476d7f',borderRadius:9,marginTop:9,fontSize:12}}>
   <div style={{color:'#a8d9ed',fontWeight:800}}>{listing.state==='programming-slot'?'CHANNEL SLOT • FEED NOT CONNECTED':listing.state==='feed-listed'?'PROGRAM LISTED • PLAYBACK UNVERIFIED':'NETWORK REGISTERED • NO VERIFIED PROGRAM'}</div>
   <div style={{fontWeight:700,marginTop:4}}>{listing.title}</div>
   <div style={{marginTop:4,color:'#acc6d5'}}>{listing.sourceLabel}</div>
   <div style={{marginTop:6,fontSize:11}}>This dial changes the selected network; it does not start an unverified stream.</div>
  </div>
  <div style={{display:'flex',flexWrap:'wrap',gap:7,marginTop:10}}>
   {preset.route&&<a href={preset.route} style={{...control,textDecoration:'none',display:'inline-flex',alignItems:'center'}}>OPEN {preset.label.toUpperCase()}</a>}
   <button style={control} onClick={()=>window.dispatchEvent(new Event('tryamm:broadcast-os-request'))}>REFRESH GUIDE</button>
  </div>
  {preset.id==='free-tv'&&<div style={{padding:10,marginTop:10,border:'1px solid #4a747c',borderRadius:9}}>
   <div style={{fontWeight:800}}>TRYAMM FREE TV • AD-SUPPORTED</div>
   <p style={{fontSize:11,margin:'6px 0'}}>Existing Free TV commercial engine schedules approved, rights-cleared promos and sponsor spots. Viewer price: $0. No paid impressions are generated by this preview.</p>
   <button style={control} onClick={previewFreeTvBreaks}>PREVIEW FREE TV AD-BREAK PLAN</button>
   {freeTvPlan&&<div aria-live="polite" style={{fontSize:11,marginTop:7}}>Ad plan prepared: {freeTvPlan.breaks.length} break(s), approximately {freeTvPlan.estimatedAdMinutes} minutes. Playback has not started.</div>}
  </div>}
 </section>
}
