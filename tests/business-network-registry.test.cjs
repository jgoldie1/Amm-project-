'use strict';
const assert=require('node:assert/strict');
const {createBusinessRegistry,BASELINE}=require('../lib/business-network-registry');
const registry=createBusinessRegistry();
assert.equal(registry.register({id:'beautyverse-salon',name:'BeautyVerse Salon',ownerId:'owner-1',category:'beauty',consent:true}).ok,true);
assert.equal(registry.register({id:'logistics-company',name:'Logistics Company',ownerId:'owner-2',category:'logistics',consent:true}).ok,true);
assert.equal(registry.register({id:'security-company',name:'Security Company',ownerId:'owner-3',category:'security',consent:true}).ok,true);
assert.equal(registry.register({id:'medical-office',name:'Medical Office',ownerId:'owner-4',category:'healthcare',consent:true}).ok,true);
assert.equal(registry.list().length,4);
assert.equal(registry.get('beautyverse-salon').ownerId,'owner-1');
assert.equal(registry.get('logistics-company').ownerId,'owner-2');
assert.equal(registry.get('beautyverse-salon').optionalJacobieVisionPlan,'none');
assert.equal(registry.get('medical-office').status,'pending-verification');
assert.equal(registry.get('medical-office').securityBaseline,BASELINE);
assert.equal(registry.register({id:'unapproved',name:'X',ownerId:'x',category:'x'}).ok,false);
assert.equal(registry.register({id:'beautyverse-salon',name:'Imposter',ownerId:'other',category:'beauty',consent:true}).ok,false);
assert.equal(registry.register({id:'../escape',name:'Bad',ownerId:'x',category:'x',consent:true}).ok,false);
assert.equal(registry.register({id:'admin',name:'Bad',ownerId:'x',category:'x',consent:true}).ok,false);
assert.equal(registry.get('missing'),null);
console.log('Reusable business security registry: PASS (15 assertions)');
