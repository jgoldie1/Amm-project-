'use strict';
const assert=require('node:assert/strict');
const {createTenantRecordStore}=require('../lib/business-tenant-records');
const store=createTenantRecordStore();
const actor=(tenantId,role='owner')=>({id:'test-'+tenantId,active:true,memberships:[{tenantId,role,active:true}]});
const raymond=actor('raymond-jarreau'),jacobie=actor('jacobie-vision'),omni=actor('omnicare360');
assert.equal(store.put({actor:raymond,tenantId:'raymond-jarreau',recordId:'same-id',value:{label:'Raymond-only'}}).ok,true);
assert.equal(store.put({actor:jacobie,tenantId:'jacobie-vision',recordId:'same-id',value:{label:'Jacobie-only'}}).ok,true);
assert.equal(store.put({actor:omni,tenantId:'omnicare360',recordId:'same-id',value:{label:'OmniCare-only'}}).ok,true);
assert.equal(store.get({actor:raymond,tenantId:'raymond-jarreau',recordId:'same-id'}).record.label,'Raymond-only');
assert.equal(store.get({actor:jacobie,tenantId:'jacobie-vision',recordId:'same-id'}).record.label,'Jacobie-only');
assert.equal(store.get({actor:omni,tenantId:'omnicare360',recordId:'same-id'}).record.label,'OmniCare-only');
assert.equal(store.get({actor:raymond,tenantId:'jacobie-vision',recordId:'same-id'}).ok,false);
assert.equal(store.put({actor:jacobie,tenantId:'omnicare360',recordId:'same-id',value:{label:'bad'}}).ok,false);
assert.equal(store.put({actor:actor('raymond-jarreau','viewer'),tenantId:'raymond-jarreau',recordId:'x',value:{a:1}}).ok,false);
const original=store.get({actor:raymond,tenantId:'raymond-jarreau',recordId:'same-id'}).record;
original.label='mutated';
assert.equal(store.get({actor:raymond,tenantId:'raymond-jarreau',recordId:'same-id'}).record.label,'Raymond-only');
assert.equal(store.put({actor:raymond,tenantId:'raymond-jarreau',recordId:'x',value:{tenantId:'jacobie-vision',id:'override'}}).ok,true);
const stamped=store.get({actor:raymond,tenantId:'raymond-jarreau',recordId:'x'}).record;
assert.equal(stamped.tenantId,'raymond-jarreau');assert.equal(stamped.id,'x');
console.log('Business record isolation reference: PASS (12 assertions)');
